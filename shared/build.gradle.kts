// Generates `GraphQlOperations` (one const per src/commonMain/graphql/operations/<Name>.graphql)
// so the documents live in .graphql files (validated in CI) but need no runtime resource loading.
val generateGraphQlOperations by tasks.registering {
    val opsDir = layout.projectDirectory.dir("src/commonMain/graphql/operations")
    val outDir = layout.buildDirectory.dir("generated/graphql/commonMain/kotlin")
    inputs.dir(opsDir).withPropertyName("operations")
    outputs.dir(outDir).withPropertyName("generated")
    doLast {
        val files = opsDir.asFile.listFiles { f -> f.extension == "graphql" }.orEmpty().sortedBy { it.name }
        val body = StringBuilder()
        body.appendLine("// GENERATED by :shared:generateGraphQlOperations — do not edit.")
        body.appendLine("package com.tkolymp.shared.graphql")
        body.appendLine()
        body.appendLine("object GraphQlOperations {")
        for (f in files) {
            val text = f.readText().trim()
            require("\"\"\"" !in text) { "${f.name}: triple quotes are not supported" }
            val escaped = text.replace("$", "\${'$'}")
            body.appendLine("    const val ${f.nameWithoutExtension} = \"\"\"")
            body.appendLine(escaped)
            body.appendLine("\"\"\"")
        }
        body.appendLine("}")
        val out = outDir.get().asFile.resolve("com/tkolymp/shared/graphql/GraphQlOperations.kt")
        out.parentFile.mkdirs()
        out.writeText(body.toString())
    }
}

